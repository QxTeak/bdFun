#!/usr/bin/env python3
"""把实际 App 索引同步到离线编排器；不从原型反推运行时索引。"""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
source = root / 'app/src/main/assets/settings-index.json'
target = root / 'docs/settings-organizer/catalog.js'
data = json.loads(source.read_text())
target.write_text('// Generated by tools/sync-settings-catalog.py; source: app assets.\n'
                  + 'window.SETTINGS_CATALOG = ' + json.dumps(data, ensure_ascii=False, indent=2) + ';\n')
